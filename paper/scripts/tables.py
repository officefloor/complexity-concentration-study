def table_friedman(a: dict, b: dict, out: str) -> None:
    def block(title, fr):
        if not fr:
            return [f"\\multicolumn{{3}}{{l}}{{\\emph{{{title}}}: too few complete blocks}} \\\\"]
        rows = [f"\\multicolumn{{3}}{{l}}{{\\emph{{{title}}}}} \\\\",
                f"\\multicolumn{{3}}{{l}}{{\\quad $N={fr['n']}$, $k={fr['k']}$, Iman--Davenport $F={fr['F']:.1f}$, "
                f"{ptex(fr['p_F'])}, Nemenyi CD$_{{0.05}}={fr['cd_05']:.3f}$, all-tied blocks dropped {fr.get('n_tied_dropped', 0)}}} \\\\"]
        for m, rk in sorted(fr["mean_rank"].items(), key=lambda kv: kv[1]):
            rows.append(f"\\quad {sig_tex(m)} & {rk:.2f} & \\\\")
        return rows
    body = ["\\begin{tabular}{lrl}", "\\toprule", "Method & Mean rank & \\\\", "\\midrule"]
    body += block("Main run: rules by per-repository MCC against PMD GodClass on " + tex(a["primary"]["pmd_GodClass"]["chosen_signal"]), a["friedman_rules"])
    body += ["\\addlinespace"] + block("Main run: signals by per-repository AUC against PMD GodClass", a["friedman_signals"])
    body += ["\\addlinespace"] + block("MLCQ run: rules by per-repository MCC", b["friedman_rules"])
    body += ["\\addlinespace"] + block("MLCQ run: signals by per-repository AUC", b["friedman_signals"])
    body += ["\\bottomrule", "\\end{tabular}"]
    write(out, "tab_friedman.tex", "\n".join(body) + "\n")
    fr = a["friedman_rules"]
    num("friedRulesN", str(fr["n"]))
    num("friedRulesCD", f(fr["cd_05"], 2))
    for m, rk in fr["mean_rank"].items():
        num("friedRank" + "".join(p.capitalize() for p in m.split("_")), f(rk, 2))
    fs = a["friedman_signals"]
    num("friedSignalsN", str(fs["n"]))
    num("friedSignalsCD", f(fs["cd_05"], 2))
    for m, rk in fs["mean_rank"].items():
        num("friedSigRank" + "".join(p.capitalize() for p in m.split("_")), f(rk, 2))


def table_classpath(main_dir: str, out: str) -> None:
    reps = []
    for p in sorted(glob.glob(os.path.join(main_dir, "classpath", "*.json"))):
        d = json.load(open(p))
        g = d.get("rules", {}).get("GodClass", {})
        reps.append((d.get("url"), g.get("without"), g.get("with"), len(g.get("lost") or []), len(g.get("gained") or []),
                     d.get("n_java_files"), d.get("aux_classpath_entries")))
    body = ["\\begin{tabular}{lrrrrr}", "\\toprule", "Repository & Java files & Classpath entries & GodClass without & with & Flips (lost/gained) \\\\", "\\midrule"]
    tf = tu = 0
    for url, wo, wi, lost, gained, nf, ncp in reps:
        body.append(f"{tex(url)} & {nf} & {ncp} & {wo} & {wi} & {lost}/{gained} \\\\")
        tf += lost + gained
        tu += (wo or 0) + gained
    body += ["\\midrule", f"Total & & & & & {tf} of {tu} verdicts ({100 * tf / tu:.1f}\\%) \\\\" if tu else "", "\\bottomrule", "\\end{tabular}"]
    write(out, "tab_classpath.tex", "\n".join(body) + "\n")
    num("cpRepos", str(len(reps)))
    num("cpFlips", str(tf))
    num("cpUnion", str(tu))
    num("cpRate", pct(tf / tu) if tu else "--")
    if reps:
        top = max(reps, key=lambda r: r[3] + r[4])
        num("cpMaxFlips", str(top[3] + top[4]))
        num("cpMaxFlipsRepo", tex(top[0]))
    # the log: how many candidates were tried
    log = os.path.join(common.ROOT, "classpath-log.tsv")
    if os.path.exists(log):
        tried = set()
        fails = skips = 0
        for row in csv.DictReader(open(log), delimiter="\t"):
            if row["status"] in ("ok", "fail", "skip"):
                tried.add(row["full_name"])
            fails += row["status"] == "fail"
            skips += row["status"] == "skip"
        num("cpTried", str(len(tried)))
        num("cpFailed", str(fails))
        num("cpSkipped", str(skips))


def table_human(h: dict, out: str) -> None:
    """The human-label read-outs: both levels, plan-faithful population first."""
    for level, defn in (("class", "Blob"), ("method", "LongMethod")):
        for variant in ("all", "pos"):
            r = h["readouts"][f"{level}:{variant}"]
            prefix = f"hum{defn}{variant.capitalize()}"
            num(prefix + "ReposEx", str(r["repos_with_definition"]["explore"]))
            num(prefix + "ReposCo", str(r["repos_with_definition"]["confirm"]))
            num(prefix + "RevEx", str(r["reviewed_units"]["explore"]))
            num(prefix + "RevCo", str(r["reviewed_units"]["confirm"]))
            num(prefix + "PosEx", str(r["positives"]["explore"]))
            num(prefix + "PosCo", str(r["positives"]["confirm"]))
            num(prefix + "MinPosEx", str(r["repos_with_min_positives"]["explore"]))
            num(prefix + "MinPosCo", str(r["repos_with_min_positives"]["confirm"]))
            if not r.get("chosen_signal"):
                continue
            table_explore(r, level, out, f"tab_explore_{level}_{variant}.tex")
            table_confirm(r, out, f"tab_confirm_human_{level}_{variant}.tex", prefix)
            d = r.get("decision")
            if d:
                num(prefix + "Verdict", d["overall"])
                num(prefix + "Margin", f(d["margin"]))
                num(prefix + "ExploreLevel", f(d["explore_level"]))
                for k in ("macro_mcc", "micro_mcc", "macro_fpr"):
                    b = d["paired"][k]
                    kk = "".join(p.capitalize() for p in k.split("_"))
                    num(prefix + kk, f(b["value"], 3, True) if b else "--")
                    num(prefix + kk + "CI", ci(b, 3, True))
                    num(prefix + kk + "Verdict", d["verdicts"][k])
                num(prefix + "Powered", "powered" if d["powered"] else "underpowered")
                num(prefix + "NPaired", str(d["n_paired_repos"]))
                num(prefix + "NPairedMacro", str(d["n_paired_repos_macro"]))
                num(prefix + "NAucRepos", str(d["n_auc_repos"]))
    # all-candidate table, class level, plan-faithful variant
    for level, defn in (("class", "Blob"), ("method", "LongMethod")):
        r = h["readouts"][f"{level}:all"]
        allc = r.get("all_candidates_confirm") or {}
        body = ["\\begin{tabular}{llrrrrrr}", "\\toprule",
                "Signal & Family & Pooled AUC (std.) & \\multicolumn{3}{c}{modified $z \\geq 3.5$} & \\multicolumn{2}{c}{absolute, tuned on explore} \\\\",
                " & & & micro MCC & precision & recall & cut & micro MCC \\\\", "\\midrule"]
        for s in sorted(allc, key=lambda s: -(allc[s]["pooled_auc_standardised"] or 0)):
            c = allc[s]
            mark = " (chosen)" if s == r["chosen_signal"] else ""
            cut_s = '--' if c['abs_cut'] is None else f"{c['abs_cut']:g}"
            body.append(f"{sig_tex(s)}{mark} & {common.metrics.family_of(level, s)} & {f(c['pooled_auc_standardised'])} & {f(c['mad_z_micro_mcc'])} & "
                        f"{f(c['mad_z_precision'], 2)} & {f(c['mad_z_recall'], 2)} & {cut_s} & {f(c['abs_micro_mcc'])} \\\\")
        body += ["\\bottomrule", "\\end{tabular}"]
        write(out, f"tab_human_candidates_{level}.tex", "\n".join(body) + "\n")
    lm = h["label_match"]
    num("humBlobLabelled", str(lm["blob"]["labelled"]))
    num("humBlobMeasured", str(lm["blob"]["measured"]))
