"""Generate every table and every inline number of the paper as LaTeX fragments.

    paper/scripts/tables.py [--main results/<date>] [--mlcq results/mlcq] [--out paper/generated]

Reads: the harness's confirmatory analysis.json of the main run and of the MLCQ run, the main
run's dated exploratory re-analysis (the classpath validation), the registry (oracles.json), the
sample files, the classpath reports and log, labels/mlcq-summary.json, and the paper's own
reductions in paper/data (main.json, human.json, agreement.json). Writes paper/generated/*.tex:
one file per table and numbers.tex, a list of \\newcommand macros for every number quoted in the
prose, so no number in main.tex is typed by hand. Standard library only.
"""
