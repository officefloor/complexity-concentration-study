NUMBERS: dict = {}


def num(name: str, value) -> None:
    """Register an inline number for numbers.tex (name: letters only)."""
    digits = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five", "6": "Six",
              "7": "Seven", "8": "Eight", "9": "Nine"}
    name = "".join(digits.get(ch, ch) for ch in name)
    if not re.fullmatch(r"[A-Za-z]+", name):
        raise ValueError(f"macro name must be letters only: {name}")
    NUMBERS[name] = value


def f(x, nd=3, plus=False):
    if x is None:
        return "--"
    s = f"{x:+.{nd}f}" if plus else f"{x:.{nd}f}"
    return s


def pct(x, nd=1):
    return "--" if x is None else f"{100 * x:.{nd}f}\\%"


def ci(b, nd=3, plus=False):
    if not b:
        return "--"
    lo, hi = b["lo"], b["hi"]
    return f"[{f(lo, nd, plus)}, {f(hi, nd, plus)}]"


def ptex(p) -> str:
    """A p-value for a table: a bound when it underflows, scientific notation otherwise."""
    if p is None:
        return "--"
    if p < 1e-300:
        return "$p<10^{-300}$"
    s = f"{p:.2g}"
    if "e" in s:
        m, e = s.split("e")
        return f"$p={m}\\times10^{{{int(e)}}}$"
    return f"$p={s}$"


def camel(k: str) -> str:
    return "".join(p.capitalize() for p in k.split("_"))


def tex(s: str) -> str:
    return s.replace("_", "\\_").replace("%", "\\%").replace("&", "\\&").replace("#", "\\#")


def thousands(n) -> str:
    return "--" if n is None else f"{int(round(n)):,}".replace(",", "{,}")


def write(out_dir: str, name: str, body: str) -> None:
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, name), "w") as fh:
        fh.write("% generated by paper/scripts/tables.py; do not edit\n")
        fh.write(body)


