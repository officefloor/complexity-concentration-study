def table_explore(res: dict, level: str, out: str, name: str) -> None:
    sc = res["explore_scores"]
    body = ["\\begin{tabular}{llrr}", "\\toprule", "Signal & Family & Macro mean AUC & $n$ repositories \\\\", "\\midrule"]
    for s in sorted((s for s in sc if sc[s]["mean_auc"] is not None), key=lambda s: -sc[s]["mean_auc"]):
        fam = common.metrics.family_of(level, s)
        mark = " (chosen)" if s == res["chosen_signal"] else ""
        body.append(f"{sig_tex(s)}{mark} & {fam} & {f(sc[s]['mean_auc'])} & {sc[s]['n']} \\\\")
    body += ["\\bottomrule", "\\end{tabular}"]
    write(out, name, "\n".join(body) + "\n")


def mcc_rows(label: str, m: dict) -> str:
    mi = m["micro"]
    mac = m["macro"]
    return (f"{label} & {f(mac['mean']) if mac else '--'} {ci(mac)} & {f(mi['mcc'])} & {f(mi['precision'], 2)} & "
            f"{f(mi['recall'], 2)} & {f(m['macro_fpr']['mean'], 3) if m['macro_fpr'] else '--'} & "
            f"{mi['fp_in_no_god']}/{mi['n_blocks_no_god']} \\\\")


def table_confirm(res: dict, out: str, name: str, prefix: str) -> None:
    c = res["confirm"]
    best = res["chosen_signal"]
    cut = c["absolute_cutoff"]["cut"]
    zcut = c["relative_tuned"]["z_cut"]
    body = ["\\begin{tabular}{lrrrrrr}", "\\toprule",
            "Rule on " + sig_tex(best) + " & Macro MCC (95\\% CI) & Micro MCC & Precision & Recall & Macro FPR & FP in god-free repos \\\\",
            "\\midrule",
            mcc_rows("default: modified $z \\geq 3.5$", c["relative_default"]),
            mcc_rows(f"tuned absolute cutoff $\\geq {cut:g}$", c["absolute_cutoff"]["confirm"]),
            mcc_rows(f"tuned modified $z \\geq {zcut:.2f}$ (secondary)", c["relative_tuned"]["confirm"]),
            "\\bottomrule", "\\end{tabular}"]
    write(out, name, "\n".join(body) + "\n")
    r, ab = c["relative_default"], c["absolute_cutoff"]["confirm"]
    num(prefix + "Signal", f"\\texttt{{{tex(best)}}}")
    num(prefix + "Cut", f"{cut:g}")
    num(prefix + "ZCut", f"{zcut:.2f}")
    if c.get("auc_macro"):
        num(prefix + "AucMacro", f(c["auc_macro"]["mean"]))
        num(prefix + "AucMacroCI", ci(c["auc_macro"]))
        num(prefix + "AucMacroN", str(c["auc_macro"]["n"]))
    if c.get("auc_given_macro"):
        num(prefix + "AucGiven", f(c["auc_given_macro"]["mean"]))
        num(prefix + "AucGivenCI", ci(c["auc_given_macro"]))
    num(prefix + "PooledAucStd", f(c["pooled_auc_standardised"]["auc"]))
    num(prefix + "PooledAucRaw", f(c["pooled_auc_raw"]["auc"]))
    d = c["pooled_auc_difference"]["paired"]
    num(prefix + "PooledAucDiff", f(d["value"], 3, True) if d else "--")
    num(prefix + "PooledAucDiffCI", ci(d, 3, True))
    num(prefix + "PooledAucReading", c["pooled_auc_difference"]["reading"])
    num(prefix + "NPos", thousands(c["pooled_auc_standardised"]["n_pos"]))
    num(prefix + "NNeg", thousands(c["pooled_auc_standardised"]["n_neg"]))
    num(prefix + "NGodFree", str(c["pooled_auc_standardised"]["n_blocks_no_god"]))
    for tag, m in (("Rel", r), ("Abs", ab)):
        mi = m["micro"]
        num(prefix + tag + "MacroMcc", f(m["macro"]["mean"]) if m["macro"] else "--")
        num(prefix + tag + "MicroMcc", f(mi["mcc"]))
        num(prefix + tag + "Precision", f(mi["precision"], 2))
        num(prefix + tag + "Recall", f(mi["recall"], 2))
        num(prefix + tag + "Fpr", f(m["macro_fpr"]["mean"], 3) if m["macro_fpr"] else "--")
        num(prefix + tag + "FprPct", pct(m["macro_fpr"]["mean"]) if m["macro_fpr"] else "--")
        num(prefix + tag + "PooledFprPct", pct(mi["fpr"]))
        num(prefix + tag + "Flagged", thousands(mi["tp"] + mi["fp"]))
        num(prefix + tag + "Tp", thousands(mi["tp"]))
        num(prefix + tag + "Fp", thousands(mi["fp"]))
        num(prefix + tag + "FpGodFree", str(mi["fp_in_no_god"]))
        gf = m.get("god_free") or {}
        num(prefix + tag + "MeanFlagsGodFree", f(gf.get("mean_flags"), 1))


def decision_row(label: str, d: dict, arms_note=True) -> str:
    b = d["paired"]
    cells = []
    for k in ("macro_mcc", "micro_mcc", "macro_fpr"):
        x = b.get(k)
        v = d["verdicts"][k]
        decided = k in d["arms"]
        s = (f"{f(x['value'], 3, True)} {ci(x, 3, True)}" if x else "--") + f" {v}" + ("" if decided else "$^{\\dagger}$")
        cells.append(s)
    return f"{label} & " + " & ".join(cells) + f" & {f(d['margin'], 3)} & \\textbf{{{d['overall']}}} \\\\"


def table_decisions(entries: list, out: str, name: str) -> None:
    body = ["\\begin{tabular}{lp{2.9cm}p{2.9cm}p{2.9cm}rl}", "\\toprule",
            "Definition (signal) & Macro MCC & Micro MCC & Macro FPR & Margin & Verdict \\\\", "\\midrule"]
    for label, d in entries:
        body.append(decision_row(label, d))
    body += ["\\bottomrule", "\\end{tabular}"]
    write(out, name, "\n".join(body) + "\n")


